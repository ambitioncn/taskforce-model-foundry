// Export packaging: turn a succeeded training job plus an independent
// evaluation report into a single, self-describing, checksummed bundle.
//
// The gate is enforced here and not by the caller: `assertDeliverable` is the
// only door into `exportModel`, so a failed or baseline-only evaluation cannot
// be packaged at all. That is deliberate -- an export directory is the thing
// people copy around, and a bundle on disk is a claim of improvement.

import path from 'node:path';
import { copyFile } from 'node:fs/promises';
import { ensureDir, writeJson, writeFileAtomic, exists } from '../core/fsx.mjs';
import { sha256File, sha256Json, stableStringify } from '../core/hash.mjs';

export const EXPORT_FORMAT = 'tmf.export/v1';

export class ExportBlockedError extends Error {
  constructor(message, { status = null, failed = [] } = {}) {
    super(message);
    this.name = 'ExportBlockedError';
    this.code = 'EXPORT_BLOCKED';
    this.status = status;
    this.failed = failed;
  }
}

/**
 * Terminal check that an evaluation report authorises delivery.
 *
 * Throws `ExportBlockedError` for anything that is not an explicitly passed
 * gated evaluation -- missing report, baseline-only run, failed gates, or a
 * report whose verdict and gate block disagree.
 */
export function assertDeliverable(report) {
  if (!report || typeof report !== 'object') {
    throw new ExportBlockedError('export requires an evaluation report', { status: 'missing' });
  }
  const status = report.verdict?.status ?? null;
  const gatesPassed = report.gates?.passed === true;
  const eligible = report.verdict?.deliveryEligible === true;
  if (status !== 'passed' || !gatesPassed || !eligible) {
    const failed = (report.gates?.failed ?? []).map((f) => f.id ?? f.metric ?? 'gate');
    throw new ExportBlockedError(
      `export blocked: evaluation status is ${status ?? 'unknown'}${failed.length ? ` (failed gates: ${failed.join(', ')})` : ''}`,
      { status, failed },
    );
  }
  return report;
}

function metricSummary(report) {
  const m = report.metrics ?? {};
  return {
    holdoutLoss: m.tuned?.holdout?.loss ?? null,
    baselineHoldoutLoss: m.baseline?.holdout?.loss ?? null,
    holdoutLossRelativeImprovement: m.improvement?.holdoutLossRelative ?? null,
    exactMatch: m.tuned?.holdout?.exactMatch?.accuracy ?? null,
    exactMatchAbsoluteImprovement: m.improvement?.exactMatchAbsolute ?? null,
    validationLossRelativeImprovement: m.improvement?.validationLossRelative ?? null,
  };
}

function renderModelCard({ name, version, createdAt, report, artifacts, config, files }) {
  const s = metricSummary(report);
  const num = (v) => (typeof v === 'number' ? v.toFixed(6) : 'n/a');
  const pct = (v) => (typeof v === 'number' ? `${(v * 100).toFixed(2)}%` : 'n/a');
  const gateRows = (report.gates?.results ?? [])
    .map((r) => `| ${r.id} | ${r.metric} | ${r.comparator ?? ''} ${r.threshold} | ${num(r.value)} | ${r.passed ? 'pass' : 'FAIL'} |`)
    .join('\n');
  return `# Model card: ${name} ${version}

Exported ${createdAt} by taskforce-model-foundry.

## What this is

A small post-trained model produced from **synthetic data generated by this
toolkit**. It is a demonstration-scale artifact: it is not trained on real
enterprise data, and it carries no claim of fitness for production use.

- Mode: \`${config?.mode ?? artifacts?.metrics?.mode ?? 'unknown'}\`
- Backend: \`${report.backend?.id ?? 'unknown'}\`
- Base checkpoint: \`${path.basename(artifacts?.baseCheckpoint ?? 'n/a')}\`
- Delivered weights: \`${path.basename(artifacts?.adapterCheckpoint ?? artifacts?.tunedCheckpoint ?? 'n/a')}\`${artifacts?.adapterCheckpoint ? ' (adapter; requires the base checkpoint)' : ''}

## Measured results

Measured on an independent holdout split that training never saw
(independence: \`${report.independence?.verdict ?? report.independence?.status ?? 'see eval-report.json'}\`).

| metric | value |
| --- | --- |
| holdout loss (tuned) | ${num(s.holdoutLoss)} |
| holdout loss (baseline) | ${num(s.baselineHoldoutLoss)} |
| holdout loss improvement | ${pct(s.holdoutLossRelativeImprovement)} |
| exact match (tuned) | ${pct(s.exactMatch)} |
| exact match improvement | ${pct(s.exactMatchAbsoluteImprovement)} |

## Gates

| gate | metric | threshold | value | verdict |
| --- | --- | --- | --- | --- |
${gateRows || '| (none recorded) | | | | |'}

Verdict: **${report.verdict?.status}** — ${report.verdict?.summary ?? ''}

## Training data

Synthetic, generated locally. See \`data-report.json\` for the record counts,
dedupe and PII-scan results, and split digests.

## Limitations and intended use

- Demonstration and integration testing only.
- Synthetic task distribution; behaviour outside it is unmeasured.
- No safety tuning, no real-world evaluation, no production authorisation.

## Reproduce and roll back

See \`inference.md\`.

## Files

${files.map((f) => `- \`${f.path}\` (sha256 \`${f.sha256.slice(0, 16)}…\`)`).join('\n')}
`;
}

function renderInferenceDoc({ name, version, artifacts, config }) {
  const adapter = artifacts?.adapterCheckpoint;
  return `# Reproducible inference and rollback — ${name} ${version}

## Verify the bundle first

\`\`\`bash
sha256sum -c checksums.txt
\`\`\`

Every file listed in \`manifest.json\` is covered. A checksum mismatch means the
bundle was modified after export: do not load it.

## Load and run

\`\`\`js
import { backends } from 'taskforce-model-foundry';

const backend = await backends.resolveBackend('${config?.backend ?? 'builtin-js'}');
const handle = await backend.loadModel({
  file: 'weights/base.json',${adapter ? "\n  attachAdapter: 'weights/adapter.json'," : ''}
});
const out = await backend.generate({ handle, prompt: '<your prompt>', maxNewTokens: 34 });
\`\`\`

Generation defaults to temperature 0 (greedy) and is deterministic, so the same prompt and the
same checkpoint files reproduce the same completion. The metrics in
\`model-card.md\` were produced by exactly this path; re-running the evaluation
against \`eval-report.json\`'s lineage digests should reproduce them.

## Roll back

${adapter
      ? `This export is an **adapter**. To roll back, stop loading
\`weights/adapter.json\` and serve \`weights/base.json\` alone — the base weights
are byte-identical to the pre-training checkpoint (see \`lineage.baseCheckpoint\`
in \`manifest.json\`), so rollback needs no retraining and no other artifact.`
      : `This export is a **full tuned checkpoint**. To roll back, serve
\`weights/base.json\`, which is the pre-training checkpoint shipped in this same
bundle for exactly that purpose.`}

Rollback is complete when the served checksum matches \`weights/base.json\` in
\`checksums.txt\`.
`;
}

/**
 * Package a succeeded training job into `outDir`.
 *
 * Requires an evaluation report that passed its gates; see `assertDeliverable`.
 * Returns the manifest, the per-file checksums, and a bundle digest.
 */
export async function exportModel({
  outDir,
  artifacts,
  evalReport,
  config = null,
  name = config?.project ?? 'taskforce-model',
  version = '0.1.0',
  toolkitVersion = null,
  clock = () => new Date().toISOString(),
}) {
  if (!outDir) throw new Error('exportModel requires outDir');
  if (!artifacts?.baseCheckpoint) throw new Error('exportModel requires training artifacts with a baseCheckpoint');
  assertDeliverable(evalReport);

  const createdAt = clock();
  const root = path.resolve(outDir);
  await ensureDir(path.join(root, 'weights'));

  const copies = [
    { from: artifacts.baseCheckpoint, to: 'weights/base.json', role: 'base' },
    artifacts.adapterCheckpoint ? { from: artifacts.adapterCheckpoint, to: 'weights/adapter.json', role: 'adapter' } : null,
    artifacts.tunedCheckpoint ? { from: artifacts.tunedCheckpoint, to: 'weights/tuned.json', role: 'tuned' } : null,
    artifacts.dataReportFile ? { from: artifacts.dataReportFile, to: 'data-report.json', role: 'data-report' } : null,
    evalReport.reportFile ? { from: evalReport.reportFile, to: 'eval-report.json', role: 'eval-report' } : null,
  ].filter(Boolean);

  const files = [];
  for (const copy of copies) {
    if (!(await exists(copy.from))) throw new Error(`exportModel: missing input ${copy.role}: ${copy.from}`);
    const dest = path.join(root, copy.to);
    await copyFile(copy.from, dest);
    files.push({ path: copy.to, role: copy.role, sha256: await sha256File(dest), source: copy.from });
  }
  if (!evalReport.reportFile) {
    const dest = path.join(root, 'eval-report.json');
    await writeJson(dest, evalReport);
    files.push({ path: 'eval-report.json', role: 'eval-report', sha256: await sha256File(dest), source: 'inline' });
  }

  const lineage = {
    data: {
      dataDir: artifacts.dataDir ?? null,
      reportFile: artifacts.dataReportFile ?? null,
      splits: evalReport.inputs?.splits ?? null,
      datasets: config?.data?.datasets ?? null,
      synthetic: true,
    },
    parameters: {
      mode: config?.mode ?? null,
      seed: config?.seed ?? null,
      model: config?.model ?? null,
      hyper: config?.hyper ?? null,
      trainBudget: config?.trainBudget ?? null,
    },
    training: {
      jobId: artifacts.jobId ?? null,
      metrics: artifacts.metrics ?? null,
    },
    evaluation: {
      jobId: evalReport.jobId ?? null,
      reportDigest: evalReport.reportDigest ?? null,
      independence: evalReport.independence ?? null,
      gates: evalReport.gates?.results ?? [],
      lineage: evalReport.lineage ?? null,
    },
    baseCheckpoint: files.find((f) => f.role === 'base')?.sha256 ?? null,
  };

  const manifest = {
    format: EXPORT_FORMAT,
    name,
    version,
    createdAt,
    toolkit: { name: 'taskforce-model-foundry', version: toolkitVersion },
    kind: artifacts.adapterCheckpoint ? 'adapter' : 'full',
    backend: evalReport.backend ?? null,
    metrics: metricSummary(evalReport),
    verdict: evalReport.verdict ?? null,
    lineage,
    files,
    rollback: artifacts.adapterCheckpoint
      ? 'serve weights/base.json alone; the adapter is additive and removing it restores pre-training behaviour'
      : 'serve weights/base.json, the pre-training checkpoint shipped in this bundle',
    docs: ['model-card.md', 'inference.md'],
  };

  const card = renderModelCard({ name, version, createdAt, report: evalReport, artifacts, config, files });
  await writeFileAtomic(path.join(root, 'model-card.md'), card);
  const inference = renderInferenceDoc({ name, version, artifacts, config });
  await writeFileAtomic(path.join(root, 'inference.md'), inference);

  for (const doc of ['model-card.md', 'inference.md']) {
    files.push({ path: doc, role: 'doc', sha256: await sha256File(path.join(root, doc)), source: 'generated' });
  }

  manifest.bundleDigest = sha256Json(files.map((f) => [f.path, f.sha256]));
  const manifestFile = path.join(root, 'manifest.json');
  await writeJson(manifestFile, manifest);

  const checksums = `${files.map((f) => `${f.sha256}  ${f.path}`).join('\n')}\n${await sha256File(manifestFile)}  manifest.json\n`;
  await writeFileAtomic(path.join(root, 'checksums.txt'), checksums);

  return {
    outDir: root,
    manifestFile,
    manifest,
    files,
    bundleDigest: manifest.bundleDigest,
    checksumsFile: path.join(root, 'checksums.txt'),
    stable: stableStringify({ digest: manifest.bundleDigest }),
  };
}
